import 'package:flutter/material.dart';

import '../../../core/models/payment_receipt.dart';
import 'portal_widgets.dart';

/// The resident's receipt for one payment.
///
/// Rendered from the server's receipt (`GET /payments/:id/receipt`), the same
/// artifact the office prints: the reference, the amount, the method, the
/// date and the invoice it settles, with the server's own status. Nothing on
/// this card is computed on the client, and a value the server did not send
/// is reported as "not reported" rather than filled in.
class PaymentReceiptCard extends StatelessWidget {
  const PaymentReceiptCard({
    super.key,
    required this.receipt,
    this.title = 'Payment receipt',
  });

  final PaymentReceipt receipt;

  /// The heading of the artifact.
  final String title;

  @override
  Widget build(BuildContext context) {
    final cs = Theme.of(context).colorScheme;
    final text = Theme.of(context).textTheme;
    final amount = receipt.amount;

    return Card(
      margin: EdgeInsets.zero,
      child: Padding(
        padding: const EdgeInsets.all(16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            if (receipt.pgName.isNotEmpty) ...[
              Text(
                receipt.pgName,
                textAlign: TextAlign.center,
                style: text.titleSmall?.copyWith(fontWeight: FontWeight.w800),
              ),
              const SizedBox(height: 8),
            ],
            Text(
              title,
              textAlign: TextAlign.center,
              style: text.titleMedium?.copyWith(fontWeight: FontWeight.w800),
            ),
            const SizedBox(height: 2),
            Text(
              'Ref ${receipt.id}',
              textAlign: TextAlign.center,
              style: TextStyle(
                fontSize: 11,
                fontFamily: 'monospace',
                color: cs.onSurfaceVariant,
              ),
            ),
            const SizedBox(height: 12),
            Text(
              amount == null
                  ? 'Amount not reported by the server'
                  : formatMoney(amount),
              textAlign: TextAlign.center,
              style: text.headlineSmall?.copyWith(
                fontWeight: FontWeight.w800,
                color: cs.primary,
              ),
            ),
            const SizedBox(height: 6),
            Center(child: StatusChip(label: receipt.status)),
            const SizedBox(height: 12),
            const Divider(),
            const SizedBox(height: 4),
            _line(context, 'Tenant', receipt.tenantName),
            if (receipt.roomNumber.isNotEmpty)
              _line(context, 'Room', receipt.roomNumber),
            _line(context, 'Invoice', receipt.invoiceNumber),
            _line(context, 'Method', receipt.method),
            if (receipt.type.isNotEmpty) _line(context, 'Type', receipt.type),
            if (receipt.utrNumber != null && receipt.utrNumber!.isNotEmpty)
              _line(context, 'UTR / Ref', receipt.utrNumber!),
            _line(context, 'Date', formatDate(receipt.date)),
            if (receipt.notes != null && receipt.notes!.isNotEmpty) ...[
              const SizedBox(height: 8),
              Text(
                'Notes: ${receipt.notes}',
                style: TextStyle(fontSize: 12, color: cs.onSurfaceVariant),
              ),
            ],
            const SizedBox(height: 12),
            const Divider(),
            const SizedBox(height: 8),
            Text(
              'Generated by the PG management system.',
              textAlign: TextAlign.center,
              style: TextStyle(fontSize: 11, color: cs.onSurfaceVariant),
            ),
          ],
        ),
      ),
    );
  }

  Widget _line(BuildContext context, String label, String value) {
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 4),
      child: Row(
        mainAxisAlignment: MainAxisAlignment.spaceBetween,
        children: [
          Text(
            label,
            style: TextStyle(
              color: Theme.of(context).colorScheme.onSurfaceVariant,
              fontWeight: FontWeight.w600,
            ),
          ),
          Flexible(
            child: Text(
              value.isEmpty ? 'not reported' : value,
              textAlign: TextAlign.end,
              style: const TextStyle(fontWeight: FontWeight.w700),
            ),
          ),
        ],
      ),
    );
  }
}
