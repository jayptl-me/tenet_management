'use client';

import { clsx } from 'clsx';
import { Button } from '@/components/ui/Button';
import { surfaceCardClass } from '@/lib/field-styles';

// ── Types ──────────────────────────────────────────────

export interface ReceiptLine {
  label: string;
  value: string;
  mono?: boolean;
}

export interface PgBranding {
  pgName?: string;
  tagline?: string;
  address?: {
    line1?: string;
    line2?: string;
    city?: string;
    state?: string;
    pincode?: string;
  };
  phone?: string;
  email?: string;
  gstNumber?: string;
  upiId?: string;
  upiPayeeName?: string;
}

export interface ReceiptDocumentProps {
  title: string;
  reference: string;
  statusLabel: string;
  amount: string;
  lines: ReceiptLine[];
  notes?: string;
  footerNote?: string;
  className?: string;
  pgBranding?: PgBranding | null;
  /** Hides on-screen action buttons (used when embedded elsewhere). */
  showActions?: boolean;
  onPrint?: () => void;
  onClose?: () => void;
}

/**
 * Server payload of `GET /payments/:id/receipt`. Every receipt on screen is
 * rendered from this shape, so a receipt can never show a number the server
 * did not send.
 */
export interface PaymentReceiptSource {
  _id: string;
  amount: number;
  method?: string;
  type?: string;
  status?: string;
  notes?: string;
  paidAt?: string;
  createdAt?: string;
  utrNumber?: string;
  invoiceId?:
    | string
    | {
        _id?: string;
        invoiceNumber?: string;
        month?: string;
        totalAmount?: number;
      };
  tenantId?: {
    _id?: string;
    userId?: { name?: string; phone?: string };
    roomId?: { roomNumber?: string };
  };
}

/** Ready-to-render receipt content derived from a server receipt. */
export interface PaymentReceiptContent {
  title: string;
  reference: string;
  statusLabel: string;
  amount: string;
  lines: ReceiptLine[];
  notes?: string;
  footerNote: string;
}

function formatCurrency(amount: number | null | undefined): string {
  if (amount == null) return '₹0';
  try {
    return '₹' + amount.toLocaleString('en-IN');
  } catch {
    return '₹' + amount;
  }
}

function formatMethod(method: string): string {
  return method.replace(/_/g, ' ');
}

function formatType(type: string): string {
  return type.charAt(0).toUpperCase() + type.slice(1);
}

function formatStatusLabel(status: string): string {
  return status.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
}

function formatDateTime(dateStr: string | null | undefined): string {
  if (!dateStr) return 'N/A';
  try {
    return new Date(dateStr).toLocaleString('en-IN', {
      day: '2-digit',
      month: 'short',
      year: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    });
  } catch {
    return dateStr;
  }
}

function receiptInvoiceNumber(receipt: PaymentReceiptSource): string {
  if (!receipt.invoiceId) return 'N/A';
  if (typeof receipt.invoiceId === 'string') return receipt.invoiceId;
  return receipt.invoiceId.invoiceNumber ?? receipt.invoiceId._id ?? 'N/A';
}

/**
 * Builds the receipt document content from the server-issued payment receipt.
 * One builder for every surface that shows a payment receipt, so the artifact
 * cannot drift between the payment detail page and the record-payment flow.
 */
export function buildPaymentReceipt(receipt: PaymentReceiptSource): PaymentReceiptContent {
  return {
    title: 'Payment Receipt',
    reference: `Ref ${receipt._id}`,
    statusLabel: formatStatusLabel(receipt.status ?? 'N/A'),
    amount: formatCurrency(receipt.amount),
    lines: [
      { label: 'Tenant', value: receipt.tenantId?.userId?.name ?? 'N/A' },
      { label: 'Room', value: receipt.tenantId?.roomId?.roomNumber ?? 'N/A' },
      { label: 'Invoice', value: receiptInvoiceNumber(receipt) },
      { label: 'Method', value: receipt.method ? formatMethod(receipt.method) : 'N/A' },
      { label: 'Type', value: receipt.type ? formatType(receipt.type) : 'N/A' },
      ...(receipt.utrNumber ? [{ label: 'UTR', value: receipt.utrNumber, mono: true }] : []),
      {
        label: 'Paid at',
        value: formatDateTime(receipt.paidAt ?? receipt.createdAt),
      },
    ],
    notes: receipt.notes || undefined,
    footerNote: 'This receipt was generated by the PG management system.',
  };
}

// ── Component ──────────────────────────────────────────

/**
 * Print-optimized receipt document. `window.print()` prints ONLY this
 * subtree (globals.css hides everything else via .receipt-print-area).
 */
export function ReceiptDocument({
  title,
  reference,
  statusLabel,
  amount,
  lines,
  notes,
  footerNote,
  className,
  pgBranding,
  showActions = true,
  onPrint,
  onClose,
}: ReceiptDocumentProps) {
  const addressParts = [
    pgBranding?.address?.line1,
    pgBranding?.address?.line2,
    pgBranding?.address?.city,
    pgBranding?.address?.state,
    pgBranding?.address?.pincode,
  ].filter(Boolean);

  return (
    <div className={clsx('receipt-print-area', className)}>
      <div className={clsx(surfaceCardClass, 'overflow-hidden')}>
        {/* Receipt head */}
        <div className="border-b border-(--border-color) px-6 pt-6 pb-4 text-center">
          {pgBranding?.pgName && (
            <div className="mb-3 space-y-0.5 border-b border-(--border-color) pb-3">
              <p className="font-display text-base font-bold tracking-tight text-(--color-text-primary)">
                {pgBranding.pgName}
              </p>
              {addressParts.length > 0 && (
                <p className="text-11 text-(--color-text-muted)">{addressParts.join(', ')}</p>
              )}
              <div className="text-10 flex flex-wrap items-center justify-center gap-2 text-(--color-text-muted)">
                {pgBranding.phone && <span>Tel: {pgBranding.phone}</span>}
                {pgBranding.email && <span>Email: {pgBranding.email}</span>}
                {pgBranding.gstNumber && <span>GSTIN: {pgBranding.gstNumber}</span>}
              </div>
            </div>
          )}
          <p className="font-display text-sm font-bold tracking-tight text-(--color-text-primary)">
            {title}
          </p>
          <p className="text-11 mt-0.5 font-mono text-(--color-text-muted)">{reference}</p>
          <p className="font-display mt-4 text-3xl font-bold tracking-tight text-(--color-text-primary) tabular-nums">
            {amount}
          </p>
          <p className="mt-1 text-xs font-semibold text-(--color-text-secondary)">{statusLabel}</p>
        </div>

        {/* Receipt body */}
        <dl className="divide-y divide-(--border-color) px-6">
          {lines.map((line) => (
            <div key={line.label} className="flex items-baseline justify-between gap-4 py-2.5">
              <dt className="text-13 font-medium text-(--color-text-muted)">{line.label}</dt>
              <dd
                className={clsx(
                  'text-13 text-right font-semibold text-(--color-text-primary)',
                  line.mono && 'font-mono text-xs',
                )}
              >
                {line.value}
              </dd>
            </div>
          ))}
        </dl>

        {notes && (
          <div className="border-t border-(--border-color) px-6 py-3">
            <p className="text-11 font-semibold tracking-wide text-(--color-text-muted) uppercase">
              Notes
            </p>
            <p className="text-13 mt-1 leading-relaxed whitespace-pre-wrap text-(--color-text-secondary)">
              {notes}
            </p>
          </div>
        )}

        {footerNote && (
          <p className="text-11 border-t border-(--border-color) px-6 py-3 text-center text-(--color-text-muted)">
            {footerNote}
          </p>
        )}

        {showActions && (
          <div className="receipt-print-no-print flex justify-end gap-2 border-t border-(--border-color) px-6 py-4">
            {onClose && (
              <Button variant="outline" onClick={onClose}>
                Close
              </Button>
            )}
            {onPrint && (
              <Button variant="primary" onClick={onPrint}>
                Print / Save PDF
              </Button>
            )}
          </div>
        )}
      </div>
    </div>
  );
}
